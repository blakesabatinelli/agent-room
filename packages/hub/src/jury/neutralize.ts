import type { AgentConfig, Task } from "@agent-room/shared";
import { PERSONA_BEGIN, PERSONA_END } from "../control/context.js";

/**
 * 2.2 AC1: an output is rewritten into a neutral voice before anyone judges it, because models recognise
 * and favour their own writing. Files the task wrote are judged as files and never pass through here; the
 * agent's chat reply does.
 *
 * Order: persona blocks and sign-offs are removed mechanically first (so a persona's voice never reaches the
 * rewriter), then a model rewrites the rest, and the rewrite is only used if it kept every number and file
 * reference. Without a rewriter the mechanical pass alone is the result.
 */

export type RewriteFn = (prompt: string) => Promise<string | undefined>;

export interface Neutral {
  text: string;
  /** model = a rewriter's text was used; mechanical = no model (or its rewrite was refused); empty = nothing to rewrite. */
  how: "model" | "mechanical" | "empty";
  note?: string;
}

const PERSONA_RE = new RegExp(`${esc(PERSONA_BEGIN)}[\\s\\S]*?${esc(PERSONA_END)}`, "g");
function esc(s: string) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }

/** Anything between the persona markers, and stray markers on their own. */
export function stripPersona(text: string): string {
  return text.replace(PERSONA_RE, "").split(PERSONA_BEGIN).join("").split(PERSONA_END).join("");
}

const OPENER = /^\s*(sure|certainly|absolutely|of course|great question|happy to help|no problem)[!,.:]\s*/i;
/** A line that only signs the work: "— Claude", "-- Codex", "Signed, X", "Best regards,", "Hope this helps!". */
const SIGN_OFF = /^\s*(?:(?:—|–|--)\s*\p{L}[\p{L}\d.'_-]*(?:\s+[\p{L}\d.'_-]+){0,2}|(?:signed|sent by|written by|generated by|posted by)\b.{0,50}|(?:best|kind|warm)?\s*(?:regards|wishes)\b.{0,40}|cheers|thanks|thank you|sincerely|hope this helps|let me know if\b.*|happy to (?:help|elaborate)\b.*|feel free to\b.*)[!.,]?\s*$/iu;

/** Emphasis markers around words, outside code. */
function plainEmphasis(s: string): string {
  return s
    .replace(/\*\*(?=\S)([^*\n]+?)(?<=\S)\*\*/g, "$1")
    .replace(/__(?=\S)([^_\n]+?)(?<=\S)__/g, "$1")
    .replace(/(?<![\w*])\*(?=[^\s*])([^*\n]+?)(?<=[^\s*])\*(?![\w*])/g, "$1")
    .replace(/(?<![\w_])_(?=[^\s_])([^_\n]+?)(?<=[^\s_])_(?![\w_])/g, "$1");
}

/** Apply `fn` to the text outside fenced code and inline code spans, which stay exactly as written. */
function outsideCode(text: string, fn: (s: string) => string): string {
  return text.split(/(```[\s\S]*?```|`[^`\n]+`)/g).map((part, i) => (i % 2 ? part : fn(part))).join("");
}

function dropSelfIntro(text: string, names: string[]): string {
  let out = text;
  for (const n of names) {
    const e = esc(n);
    out = out.replace(new RegExp(`\\bI(?:'m| am) ${e}\\b[,.]?\\s*`, "gi"), "")
      .replace(new RegExp(`^\\s*${e} here[:,]\\s*`, "gim"), "");
  }
  return out;
}

/** The names an agent signs with. */
export function selfNames(worker?: Pick<AgentConfig, "name" | "id" | "provider">): string[] {
  if (!worker) return [];
  return [...new Set([worker.name, worker.id, worker.provider].filter((n): n is string => !!n && n.length >= 3))];
}

/** No model needed: persona blocks, sign-offs, openers, emphasis, emoji and spacing. Facts, numbers and code are untouched. */
export function mechanical(text: string, worker?: Pick<AgentConfig, "name" | "id" | "provider">): string {
  let t = stripPersona(text ?? "").replace(/\r\n?/g, "\n");
  t = outsideCode(t, (s) => dropSelfIntro(s, selfNames(worker)));
  // Sign-offs sit at the end: look at the last few non-empty lines only.
  const lines = t.split("\n");
  let seen = 0;
  for (let i = lines.length - 1; i >= 0 && seen < 4; i--) {
    if (!lines[i].trim()) continue;
    seen++;
    if (SIGN_OFF.test(lines[i])) { lines.splice(i, 1); seen--; }
    else break; // stop at the first line of real content
  }
  t = lines.join("\n");
  t = t.replace(OPENER, "");
  t = outsideCode(t, (s) => plainEmphasis(s)
    .replace(/^[ \t]*#{1,6}[ \t]+/gm, "")
    .replace(/\p{Extended_Pictographic}️?/gu, "")
    .replace(/ [—–] /g, " - ")
    .replace(/[ \t]+$/gm, "")
    .replace(/[ \t]{2,}/g, " "));
  return t.replace(/\n{3,}/g, "\n\n").trim();
}

/** What a rewrite must keep: numbers and file references (words with an extension, or paths) from the source text. */
export function factsOf(text: string): string[] {
  const out = new Set<string>();
  for (const m of text.matchAll(/\d[\d,.]*\d|\d/g)) out.add(m[0].replace(/[.,]+$/, "").replace(/,/g, ""));
  for (const m of text.matchAll(/[\w@~-]+(?:[./][\w@-]+)*\.[A-Za-z][\w]{0,7}\b|(?:[\w-]+\/)+[\w.-]+/g)) out.add(m[0]);
  for (const m of text.matchAll(/`([^`\n]{1,80})`/g)) out.add(m[1]);
  return [...out];
}

/** Why a rewrite can't be used, or undefined when it keeps what the source said. */
export function rewriteProblem(source: string, rewrite: string): string | undefined {
  const r = rewrite.trim();
  if (!r) return "the rewrite was empty";
  if (/^\[\[\w+\]\]/.test(r) || r.includes('"""')) return "the rewrite repeated the instructions";
  if (source.length > 200 && r.length < source.length * 0.4) return "the rewrite was much shorter than the original";
  if (r.length > source.length * 2 + 400) return "the rewrite was much longer than the original";
  const flat = r.replace(/,/g, "");
  const missing = factsOf(source).filter((f) => !r.includes(f) && !flat.includes(f.replace(/,/g, "")));
  if (missing.length) return `the rewrite dropped ${missing.slice(0, 3).join(", ")}${missing.length > 3 ? ` and ${missing.length - 3} more` : ""}`;
  return undefined;
}

export const neutralizePrompt = (text: string, task: Pick<Task, "title">) => `[[NEUTRALIZE]]
You rewrite one agent's reply into a neutral voice, so a reviewer can't tell which model or persona wrote it.
Keep every fact, number, name, file reference, command, quoted string, code block and claim exactly as given,
including doubts and caveats. Never add anything, never drop anything, never fix or judge the content.
Change only the style: plain, flat prose in the same order. Remove first-person talk about the writer
("I", "as an AI", its name), greetings, sign-offs, signatures, persona voice, jokes, emoji, bold used for
emphasis and model-typical phrasing. Keep lists as plain lists and keep code untouched.
Reply with the rewritten text only.

The reply is about the task "${task.title}".
"""
${text}
"""`;

/**
 * AC1: the output the judges see. `rewrite` is a call to the chosen rewriter (a local model when there is one);
 * leave it out for the mechanical pass alone.
 */
export async function neutralize(
  output: string, task: Pick<Task, "title">, opts: { worker?: Pick<AgentConfig, "name" | "id" | "provider">; rewrite?: RewriteFn } = {},
): Promise<Neutral> {
  const base = mechanical(output, opts.worker);
  if (!base) return { text: "", how: "empty" };
  if (!opts.rewrite) return { text: base, how: "mechanical" };
  let out: string | undefined;
  try { out = await opts.rewrite(neutralizePrompt(base, task)); } catch { out = undefined; }
  if (!out) return { text: base, how: "mechanical", note: "the rewriter gave no answer" };
  const problem = rewriteProblem(base, out);
  if (problem) return { text: base, how: "mechanical", note: problem };
  // The rewriter saw no persona text, but make sure nothing came back in.
  return { text: mechanical(out, opts.worker), how: "model" };
}
